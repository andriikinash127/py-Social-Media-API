from django.urls import path

from .views import (
    FollowersListView,
    FollowingListView,
    FollowUserView,
    ProfileView,
    PublicProfileView,
    UserLoginView,
    UserLogoutView,
    UserRegistrationView,
    UserSearchView,
)

urlpatterns = [
    path(
        "register/",
        UserRegistrationView.as_view(),
        name="user-register",
    ),
    path(
        "login/",
        UserLoginView.as_view(),
        name="user-login",
    ),
    path(
        "logout/",
        UserLogoutView.as_view(),
        name="user-logout",
    ),
    path(
        "me/",
        ProfileView.as_view(),
        name="my-profile",
    ),
    path(
        "profiles/<str:username>/",
        PublicProfileView.as_view(),
        name="public-profile",
    ),
    path(
        "search/",
        UserSearchView.as_view(),
        name="user-search",
    ),
    path(
        "follow/<str:username>/",
        FollowUserView.as_view(),
        name="user-follow",
    ),
    path(
        "following/",
        FollowingListView.as_view(),
        name="following-list",
    ),
    path(
        "followers/",
        FollowersListView.as_view(),
        name="followers-list",
    ),
]
